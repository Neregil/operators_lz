n=int(input("Проверка на то, простое ли число: "))
m=2 #Вводим делитель
while m<=int((n**0.5)) and n%m!=0: m=m+1 #Цикл в котором мы идём по нему до тех пор, пока наш делитель меньше корня нашего проверяемого числа, и если условия удовлетворяются мы увеличиваем наш делитель
if m>int((n**0.5)): print('Y') #Если наш делитель достиг предела это значит у нашего чила не нашлось делителей до корня из числа, и значит оно простое
else: print('N')